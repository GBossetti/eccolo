const SUPPORTED = ['en', 'es', 'it', 'ca'];
const DEFAULT   = 'en';

function getLang() {
  const param = new URLSearchParams(location.search).get('lang');
  if (param && SUPPORTED.includes(param)) return param;
  const browser = navigator.language.slice(0, 2);
  return SUPPORTED.includes(browser) ? browser : DEFAULT;
}

function applyLang(lang) {
  const t = translations[lang] || translations[DEFAULT];

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    if (t[key] !== undefined) el.textContent = t[key];
  });

  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.dataset.i18nHtml;
    if (t[key] !== undefined) el.innerHTML = t[key];
  });

  document.documentElement.lang = lang;

  document.querySelectorAll('.lang-btn').forEach(btn => {
    const active = btn.dataset.lang === lang;
    btn.classList.toggle('is-active', active);
    btn.setAttribute('aria-pressed', active ? 'true' : 'false');
  });
}

function setLang(lang) {
  const url = new URL(location.href);
  url.searchParams.set('lang', lang);
  history.pushState({}, '', url);
  applyLang(lang);
}

window.setLang = setLang;

const LANG_NAMES = { en: 'English', es: 'Español', it: 'Italiano', ca: 'Català' };

(function buildSwitcher() {
  const switcher = document.querySelector('.lang-switcher');
  if (!switcher) return;
  switcher.setAttribute('role', 'group');
  switcher.setAttribute('aria-label', 'Language selector');
  SUPPORTED.forEach((lang, i) => {
    if (i > 0) {
      const dot = document.createElement('span');
      dot.className = 'lang-dot';
      dot.textContent = '·';
      dot.setAttribute('aria-hidden', 'true');
      switcher.appendChild(dot);
    }
    const btn = document.createElement('button');
    btn.className = 'lang-btn';
    btn.dataset.lang = lang;
    btn.textContent = lang.toUpperCase();
    btn.setAttribute('aria-label', `Switch to ${LANG_NAMES[lang]}`);
    btn.setAttribute('aria-pressed', 'false');
    btn.addEventListener('click', () => setLang(lang));
    switcher.appendChild(btn);
  });
})();

applyLang(getLang());
